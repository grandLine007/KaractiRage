anim("rpg_slime_hop", { w: 16, h: 16, frames: 6, fps: 8, outline: "k" }, (c) => {
  const sq = Math.abs(Math.sin(c.phase * Math.PI * 2))
  const rx = 6 - Math.round(sq * 1)
  const ry = 5 + Math.round(sq * 2)
  c.ellipse(7, 7, rx, ry, "g")
  c.ellipse(7, 7, Math.max(2, rx - 2), Math.max(2, ry - 2), "G")
  c.px(5, 6, "w")
  c.px(8, 6, "w")
})
